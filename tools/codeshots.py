def font(path, px):
    return ImageFont.truetype(path, max(6, int(round(px * K))))


def mix(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))


def encode(frames, out):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    enc = subprocess.Popen(["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", "%dx%d" % (W, H), "-r", "24", "-i", "-",
                            "-c:v", "libx264", "-preset", "medium", "-crf", "14", "-pix_fmt", "yuv420p", out], stdin=subprocess.PIPE)
    for f in frames:
        enc.stdin.write(f.convert("RGB").tobytes())
    enc.stdin.close()
    enc.wait()
    print("wrote %s, %d frames" % (os.path.relpath(out, V.ROOT), len(frames)))


def annotate(img, lines, color, at=(0.045, 0.115)):
    """The grey note a rendered frame carries: what drew it, or where its data came from."""
    d = ImageDraw.Draw(img)
    f = font(F_MONO, 13)
    y = at[1] * H
    for ln in lines:
        d.text((at[0] * W, y), ln, font=f, fill=color)
        y += 19 * K


def seamless(bg, fall=0.07):
    """A seamless studio background: the colour, a little darker toward the corners."""
    yy, xx = np.mgrid[0:H, 0:W]
    r = (((xx - W / 2) / (W / 2)) ** 2 + ((yy - H / 2) / (H / 2)) ** 2) ** 0.9
    a = np.array(bg, np.float32)[None, None, :] * (1 - fall * np.clip(r, 0, 2)[..., None])
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))


# ------------------------------------------------------------------ G02: the radial tree
def tree():
    rng = np.random.default_rng(1837)
    depth_max = 8
    nodes = []          # (depth, angle, parent index)
    kids = {}

    def grow(depth, a0, a1, parent):
        i = len(nodes)
        nodes.append((depth, (a0 + a1) / 2, parent))
        kids.setdefault(parent, []).append(i)
        if depth >= depth_max or (depth >= 3 and rng.random() < 0.10):
            return
        n = 4 if depth == 0 else (3 if rng.random() < 0.28 else 2)
        cuts = np.sort(rng.uniform(0.25, 0.75, n - 1)) if n == 2 else np.sort(rng.uniform(0.15, 0.85, n - 1))
        edges = [a0] + [a0 + (a1 - a0) * c for c in cuts] + [a1]
        for j in range(n):
            grow(depth + 1, edges[j], edges[j + 1], i)

    grow(0, 0.0, 2 * math.pi, -1)
    R = H * 0.40
    rad = lambda dep: R * (dep / depth_max) ** 0.82
    cx, cy = W / 2, H / 2
    frames = []
    for k in range(5):
        shown = [2.2, 4.0, 5.6, 7.0, 8.0][k]
        img = Image.new("RGB", (W * 2, H * 2), (0, 0, 0))            # drawn double size, then reduced
        d = ImageDraw.Draw(img)
        P = lambda r, a: (2 * (cx + r * math.cos(a)), 2 * (cy + r * math.sin(a)))
        for i, (dep, a, par) in enumerate(nodes):
            if dep == 0 or dep - 1 >= shown:
                continue
            col = mix(CYAN, WHITE, (dep / depth_max) ** 1.5)
            r0, r1 = rad(dep - 1), rad(min(dep, shown))
            d.line([P(r0, a), P(r1, a)], fill=col, width=max(2, int(round(2.6 * K))))
            if dep <= shown and i not in kids:
                p = P(r1, a)
                d.ellipse([p[0] - 4 * K, p[1] - 4 * K, p[0] + 4 * K, p[1] + 4 * K], fill=WHITE)
        for par, ch in kids.items():
            if par < 0 or nodes[par][0] >= shown or len(ch) < 2:
                continue
            dep = nodes[par][0]
            a0, a1 = min(nodes[c][1] for c in ch), max(nodes[c][1] for c in ch)
            r = rad(dep)
            if r < 1:
                continue
            box = [2 * (cx - r), 2 * (cy - r), 2 * (cx + r), 2 * (cy + r)]
            d.arc(box, math.degrees(a0), math.degrees(a1), fill=mix(CYAN, WHITE, (dep / depth_max) ** 1.5), width=max(2, int(round(2.6 * K))))
        d.ellipse([2 * cx - 7 * K, 2 * cy - 7 * K, 2 * cx + 7 * K, 2 * cy + 7 * K], fill=WHITE)
        img = img.resize((W, H), Image.LANCZOS)
        annotate(img, ["tree(seed=1837, depth=%d)" % depth_max, "fork: 2 or 3 at every node", "%d tips" % sum(1 for i in range(len(nodes)) if i not in kids)], GREY)
        frames.append(img)
    return frames


# ------------------------------------------------------------------ G03, G17: the ribbon
PLAN = [("helix", 14), ("loop", 5), ("strand", 7), ("turn", 3), ("strand", 7), ("loop", 4), ("helix", 9), ("free", 12)]


def backbone():
    """Alpha-carbon positions for the plan above, in angstroms. A made-up fold: no real protein is shown."""
    rng = np.random.default_rng(1196)
    pts, kind = [], []
    pos = np.array([-17.0, -6.0, 0.0])
    direction = np.array([0.9, 0.42, 0.1])
    strand_no = 0
    for name, n in PLAN:
        direction = direction / np.linalg.norm(direction)
        if name == "helix":
            u = np.cross(direction, [0.0, 0.0, 1.0])
            u /= np.linalg.norm(u)
            v = np.cross(direction, u)
            for i in range(n):
                th = math.radians(100 * i)
                pts.append(pos + direction * 1.5 * i + 2.3 * (math.cos(th) * u + math.sin(th) * v))
                kind.append("helix")
            pos = pos + direction * 1.5 * n
            direction = direction + rng.normal(0, 0.5, 3)
        elif name in ("loop", "turn"):
            bend = np.array([0.2, -1.0, 0.5]) if name == "loop" else np.array([0.0, -1.0, 0.0])
            for i in range(n):
                t = (i + 1) / (n + 1)
                direction = direction * (1 - 0.5 * t) + bend * 0.5 * t + rng.normal(0, 0.12, 3)
                direction /= np.linalg.norm(direction)
                pos = pos + direction * 3.2
                pts.append(pos.copy())
                kind.append("loop")
            if name == "turn":
                direction = -strand_dir + np.array([0.0, 0.0, 0.05])
                pos = pos + np.array([0.0, -4.4, 0.6])
        elif name == "strand":
            if strand_no == 0:
                strand_dir = np.array([0.95, -0.2, 0.15])
                strand_dir /= np.linalg.norm(strand_dir)
                direction = strand_dir
            for i in range(n):
                pos = pos + direction * 3.3
                pts.append(pos + np.array([0.0, 0.0, 0.55 * (1 if i % 2 else -1)]))
                kind.append("strand")
            strand_no += 1
            direction = direction + np.array([0.3, 0.5, 0.1])
        else:                                                  # the residues that have not found their place
            for i in range(n):
                direction = direction + rng.normal(0, 0.75, 3)
                direction /= np.linalg.norm(direction)
                pos = pos + direction * 3.7
                pts.append(pos.copy())
                kind.append("free")
    p = np.array(pts)
    return p - p.mean(axis=0), kind


def spline(p, per=8):
    out = []
    q = np.vstack([p[0], p, p[-1]])
    for i in range(1, len(q) - 2):
        for s in range(per):
            t = s / per
            out.append(0.5 * ((2 * q[i]) + (-q[i - 1] + q[i + 1]) * t + (2 * q[i - 1] - 5 * q[i] + 4 * q[i + 1] - q[i + 2]) * t * t
                              + (-q[i - 1] + 3 * q[i] - 3 * q[i + 1] + q[i + 2]) * t ** 3))
    out.append(p[-1])
    return np.array(out)


def ribbon(on_white):
    """The chain as a cartoon ribbon: helices as a band coiling round their axis, strands as flat bands lying
    in one sheet, loops as a thin cord, and the residues that have not folded as beads on a thread."""
    p, kind = backbone()
    n = len(p)
    wv = np.zeros((n, 3))
    ranges, i0 = [], 0
    for name, cnt in PLAN:
        ranges.append((name, i0, i0 + cnt))
        i0 += cnt
    strands = [(a, b) for name, a, b in ranges if name == "strand"]
    sheet_n = np.cross(p[strands[0][1] - 1] - p[strands[0][0]], p[strands[1][0]:strands[1][1]].mean(axis=0) - p[strands[0][0]:strands[0][1]].mean(axis=0))
    sheet_n /= np.linalg.norm(sheet_n)
    for name, a, b in ranges:
        if name == "helix":
            axis = p[b - 4:b].mean(axis=0) - p[a:a + 4].mean(axis=0)
            wv[a:b] = axis / np.linalg.norm(axis) * 1.75
        elif name == "strand":
            t = p[b - 1] - p[a]
            side = np.cross(sheet_n, t / np.linalg.norm(t))
            wv[a:b] = side / np.linalg.norm(side) * 2.2
    folded = [i for i, k in enumerate(kind) if k != "free"]
    free = [i for i, k in enumerate(kind) if k == "free"]
    bg = PAPER if on_white else (0, 0, 0)
    dark, light = (INK, (120, 176, 226)) if on_white else ((0, 70, 100), (236, 252, 255))
    light_dir = np.array([-0.35, -0.55, 0.76])
    light_dir /= np.linalg.norm(light_dir)
    per = 10
    frames = []
    for k in range(5):
        yaw, pitch = math.radians(-34 + 6 * k), math.radians(20)
        Ry = np.array([[math.cos(yaw), 0, math.sin(yaw)], [0, 1, 0], [-math.sin(yaw), 0, math.cos(yaw)]])
        Rx = np.array([[1, 0, 0], [0, math.cos(pitch), -math.sin(pitch)], [0, math.sin(pitch), math.cos(pitch)]])
        M = (Rx @ Ry).T
        q, wq = p @ M, wv @ M
        span = max(np.ptp(q[:, 0]) / (W * 0.62), np.ptp(q[:, 1]) / (H * 0.60))
        scale = 1.0 / span
        mid = (q[:, :2].max(axis=0) + q[:, :2].min(axis=0)) / 2
        to2 = lambda v: (2 * (W / 2 + (v[0] - mid[0]) * scale), 2 * (H * 0.53 + (v[1] - mid[1]) * scale))
        img = (seamless(bg, 0.06) if on_white else Image.new("RGB", (W, H), bg)).resize((W * 2, H * 2))
        d = ImageDraw.Draw(img)
        c = spline(q[folded], per)
        m = len(c)
        res = np.minimum(np.arange(m) / per, len(folded) - 1.0)
        lo_i, hi_i = np.floor(res).astype(int), np.minimum(np.ceil(res).astype(int), len(folded) - 1)
        frac = (res - lo_i)[:, None]
        w = wq[folded][lo_i] * (1 - frac) + wq[folded][hi_i] * frac
        tang = np.gradient(c, axis=0)
        tang /= np.linalg.norm(tang, axis=1, keepdims=True) + 1e-9
        thin = np.linalg.norm(w, axis=1) < 0.3                  # loops and turns: a cord of constant width
        cord = np.cross(tang, np.array([0.0, 0.0, 1.0]))
        cord /= np.linalg.norm(cord, axis=1, keepdims=True) + 1e-9
        w[thin] = cord[thin] * 0.5
        for _ in range(3):                                      # ease the band in and out of each helix and strand
            w[1:-1] = (w[:-2] + 2 * w[1:-1] + w[2:]) / 4
        normal = np.cross(tang, w)
        normal /= np.linalg.norm(normal, axis=1, keepdims=True) + 1e-9
        for i in np.argsort((c[:-1, 2] + c[1:, 2]) / 2):         # far quads first
            quad = [to2(c[i] - w[i]), to2(c[i] + w[i]), to2(c[i + 1] + w[i + 1]), to2(c[i + 1] - w[i + 1])]
            shade = 0.22 + 0.78 * abs(float(normal[i] @ light_dir))
            if normal[i][2] < 0:                               # the back of the band
                shade *= 0.62
            d.polygon(quad, fill=mix(dark, light, shade))
            edge = mix(dark, light, shade * 0.45) if not on_white else mix(dark, light, min(1.0, shade * 0.3))
            d.line([quad[0], quad[3]], fill=edge, width=max(2, int(round(2.4 * K))))
            d.line([quad[1], quad[2]], fill=edge, width=max(2, int(round(2.4 * K))))
        prev = to2(q[folded[-1]])
        tint = dark if on_white else CYAN
        for j, i in enumerate(free):                            # loose residues: beads on a thread
            pt = to2(q[i])
            d.line([prev, pt], fill=mix(bg, tint, 0.5), width=max(2, int(round(2.4 * K))))
            prev = pt
        for j, i in enumerate(free):
            pt = to2(q[i])
            r = (9.5 - 0.3 * j) * K
            d.ellipse([pt[0] - r, pt[1] - r, pt[0] + r, pt[1] + r], fill=bg, outline=tint, width=max(2, int(round(3.2 * K))))
        img = img.resize((W, H), Image.LANCZOS)
        annotate(img, ["chain = " + " + ".join("%s(%d)" % (a, b) for a, b in PLAN[:4]), "        + " + " + ".join("%s(%d)" % (a, b) for a, b in PLAN[4:]),
                       "folded %d of %d residues" % (len(folded), len(kind)), "a made-up fold, drawn by this code"], GREY if not on_white else mix(PAPER, INK, 0.45))
        frames.append(img)
    return frames


# ------------------------------------------------------------------ G24: the whale's clicks
def spectrogram():
    src = glob.glob(V.J("archive", "src", "H01_*.mp3"))[0]
    x = np.asarray(V.decode(src), np.float32)
    sr = V.SR
    win = int(1.6 * sr)
    env = np.abs(x)
    cs = np.concatenate([[0.0], np.cumsum(env)])
    step = sr // 20
    starts = np.arange(0, max(1, len(x) - win), step)
    s0 = int(starts[np.argmax(cs[starts + win] - cs[starts])]) if len(x) > win else 0
    seg = x[s0:s0 + win]
    n, hop = 1024, 96
    idx = np.arange(0, len(seg) - n, hop)
    frames_ = np.stack([seg[i:i + n] * np.hanning(n) for i in idx])
    mag = np.abs(np.fft.rfft(frames_, axis=1)).T               # frequency by time
    top = int(20000 / (sr / 2) * mag.shape[0])
    db = 20 * np.log10(mag[:top] + 1e-6)
    db = np.clip((db - db.max() + 72) / 72, 0, 1)[::-1]         # low frequencies at the bottom
    pw, ph = int(W * 0.60), int(H * 0.50)
    small = Image.fromarray((db * 255).astype(np.uint8)).resize((pw, ph), Image.LANCZOS)
    v = np.asarray(small).astype(np.float32) / 255
    stops = [(0.0, (0, 0, 0)), (0.35, (6, 30, 70)), (0.7, CYAN), (1.0, WHITE)]
    rgb = np.zeros(v.shape + (3,), np.float32)
    for (a, ca), (b, cb) in zip(stops[:-1], stops[1:]):
        m = (v >= a) & (v <= b)
        t = ((v - a) / (b - a))[m][:, None]
        rgb[m] = np.array(ca) * (1 - t) + np.array(cb) * t
    panel = Image.fromarray(rgb.astype(np.uint8))
    x0, y0 = (W - pw) // 2, int(H * 0.215)
    out = []
    for k in range(5):
        img = Image.new("RGB", (W, H), (0, 0, 0))
        img.paste(panel, (x0, y0))
        d = ImageDraw.Draw(img)
        f = font(F_MONO, 13)
        for khz in (0, 5, 10, 15, 20):
            y = y0 + ph - khz / 20 * ph
            d.line([x0 - 8 * K, y, x0 - 2 * K, y], fill=GREY, width=1)
            d.text((x0 - 52 * K, y - 8 * K), "%2d kHz" % khz, font=f, fill=GREY)
        px = x0 + (0.12 + 0.19 * k) * pw
        d.line([px, y0 - 6 * K, px, y0 + ph + 6 * K], fill=WHITE, width=max(1, int(round(1.5 * K))))
        annotate(img, ["sperm whale clicks, NOAA Northeast Fisheries Science Center", "%.1f s from %.1f s of the recording, 0 to 20 kHz" % (win / sr, s0 / sr),
                       "S = abs(rfft(hann(1024) * x[i:i+1024]))   # every 96 samples"], GREY, at=(0.2, 0.775))   # clear of the caption: at 0.83 its third line ran under "START THE PROOF."
        out.append(img)
    return out


# ------------------------------------------------------------------ G09: the first web page
def first_page():
    raw = open(V.J("research", "firstweb", "page.txt")).read()
    body = raw[raw.index("# World Wide Web"):]
    blocks, cur = [], None
    for ln in body.split("\n"):
        if ln.startswith("# "):
            blocks.append(("h1", ln[2:].strip()))
            cur = None
        elif not ln.strip():
            cur = None
        elif ln.startswith("    "):
            blocks.append(("dd", ln.strip()))
            cur = blocks[-1]
        elif ln.startswith("[") and (cur is None or cur[0] in ("dd", "dt")) and blocks and blocks[-1][0] in ("dd", "dt", "p") and len(blocks) > 2:
            blocks.append(("dt", ln.strip()))
            cur = blocks[-1]
        elif cur is not None:
            blocks[-1] = (cur[0], cur[1] + " " + ln.strip())
            cur = blocks[-1]
        else:
            blocks.append(("p", ln.strip()))
            cur = blocks[-1]
    img = Image.new("RGB", (W, H), (255, 255, 255))
    d = ImageDraw.Draw(img)
    left, right, y = W * 0.17, W * 0.83, H * 0.07
    size = 19.5
    f, fb = font(F_SERIF, size), font(F_SERIF_B, size * 1.75)
    lh = size * 1.22 * K

    def run(text, x0, y):
        words = []
        for part in re.split(r"(\[[^\]]+\]\([^)]+\))", text):
            m = re.match(r"\[([^\]]+)\]\([^)]+\)", part)
            for w in (m.group(1) if m else part).split():
                words.append((w, bool(m)))
        x = x0
        for w, link in words:
            wd = d.textlength(w, font=f)
            if x + wd > right and x > x0:
                x, y = x0, y + lh
            d.text((x, y), w, font=f, fill=(0, 0, 238) if link else (0, 0, 0))
            if link:
                d.line([x, y + size * K * 1.02, x + wd, y + size * K * 1.02], fill=(0, 0, 238), width=max(1, int(round(K))))
            x += wd + d.textlength(" ", font=f)
        return y + lh

    for kind, text in blocks:
        if kind == "h1":
            d.text((left, y), text, font=fb, fill=(0, 0, 0))
            y += size * 1.75 * 1.5 * K
        elif kind == "p":
            y = run(text, left, y) + lh * 0.55
        elif kind == "dt":
            y = run(text, left, y)
        else:
            y = run(text, left + W * 0.045, y)
    return img, y


# ------------------------------------------------------------------ D11: the torn-edge match
def torn():
    """The bronze's break becomes the torn edge of a sheet of paper, and the sheet is pulled away off the ink world.

    The edge is the real one: it is traced from the Met's photograph, framed as shot D09 ends. The sheet starts
    where the bronze stood and leaves to the left over five frames, uncovering the whiteboard drawing of D12."""
    Image.MAX_IMAGE_PIXELS = None
    src = Image.open(glob.glob(V.J("archive", "src", "D08_*DP105609.jpg"))[0]).convert("L")
    x0, y0, w = 1060, 430, 2900                                  # D09's last framing
    g = src.resize((W, H), Image.LANCZOS, box=(x0, y0, x0 + w, y0 + w * H / W)).filter(ImageFilter.GaussianBlur(7 * K))
    dark = np.asarray(g) < 128
    edge = np.zeros(H)
    for y in range(H):
        xs = np.nonzero(dark[y, : int(W * 0.8)])[0]
        edge[y] = xs.max() if len(xs) else 0
    edge = np.convolve(np.pad(edge, 9, mode="edge"), np.ones(19) / 19, mode="valid")
    rng = np.random.default_rng(113)
    jag = np.convolve(rng.normal(0, 5 * K, H + 30), np.ones(7) / 7, mode="same")[15:-15] + rng.normal(0, 1.4 * K, H)
    plate = Image.open(V.J("clips", "stills", "D12.png")).convert("RGB").resize((W, H), Image.LANCZOS)
    plate = Image.blend(plate, Image.new("RGB", (W, H), PAPER), 0.5)
    fibre = rng.normal(0, 2.2, (H, W)).astype(np.float32)
    xx = np.arange(W)[None, :].astype(np.float32)
    frames = []
    for k, slide in enumerate([0.0, 0.05, 0.19, 0.48, 1.02]):
        line = (edge + jag - slide * W * 1.02)[:, None]
        d = xx - line                                             # distance to the right of the torn edge
        cover = np.clip(-d + 0.5, 0, 1)                           # 1 on the sheet
        a = np.asarray(plate).astype(np.float32)
        shadow = np.clip(1 - d / (26 * K), 0, 1) * (d > 0)
        a *= (1 - 0.30 * shadow ** 1.5)[..., None]
        sheet = np.empty((H, W, 3), np.float32)
        sheet[:] = np.array([247, 245, 238], np.float32)
        sheet += fibre[..., None]
        fringe = np.clip(1 + d / (9 * K), 0, 1) * (d <= 0)        # the torn fibres along the edge catch the light
        sheet += 7 * fringe[..., None]
        sheet *= (0.965 + 0.035 * np.clip(-d / (W * 0.5), 0, 1))[..., None]
        out = a * (1 - cover[..., None]) + sheet * cover[..., None]
        frames.append(Image.fromarray(np.clip(out, 0, 255).astype(np.uint8)))
    return frames


